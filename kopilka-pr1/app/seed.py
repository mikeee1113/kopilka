def seed_if_empty(db):
    """Заполняет базу, только если в ней ещё нет категорий."""
    if db.execute("SELECT COUNT(*) FROM categories").fetchone()[0] > 0:
        return
    db.executemany(
        """INSERT INTO categories (slug, name, description, icon, icon_alt, monthly_limit, essential)
           VALUES (?, ?, ?, ?, ?, ?, ?)""",
        CATEGORIES,
    )
    cursor = db.execute(
        "INSERT INTO users (email, name, password_hash, monthly_budget, created_at) VALUES (?, ?, ?, ?, ?)",
        (DEMO_EMAIL, DEMO_NAME, hash_password(DEMO_PASSWORD), 65500, now_iso()),
    )
    user_id = cursor.lastrowid
    category_ids = {row["slug"]: row["id"] for row in db.execute("SELECT id, slug FROM categories")}
    db.executemany(
        """INSERT INTO expenses (user_id, category_id, amount, spent_on, title, note, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?)""",
        [
            (user_id, category_ids[slug], amount, spent_on, title, note, now_iso())
            for spent_on, slug, title, amount, note in EXPENSES
        ],
    )
    db.commit()
